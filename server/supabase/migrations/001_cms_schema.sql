-- UPDATE certifications RLS policy name (table was renamed)
-- ============================================================
DO $$ BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename  = 'certifications'
      AND policyname = 'Allow public read certificates'
  ) THEN
    -- Policy already exists under new name via rename, nothing to do
    NULL;
  END IF;
END $$;

-- Ensure certifications has public read
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename  = 'certifications'
      AND policyname = 'Public read certifications'
  ) THEN
    EXECUTE 'CREATE POLICY "Public read certifications" ON public.certifications FOR SELECT USING (true)';
  END IF;
END $$;
