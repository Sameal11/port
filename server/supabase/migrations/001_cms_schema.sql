-- ============================================================
-- ALTER EXISTING: projects — add CMS columns
-- ============================================================
ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS featured       boolean DEFAULT false,
  ADD COLUMN IF NOT EXISTS visible        boolean DEFAULT true,
  ADD COLUMN IF NOT EXISTS display_order  integer DEFAULT 0,
  ADD COLUMN IF NOT EXISTS source         text    DEFAULT 'manual',   -- 'manual' | 'github'
  ADD COLUMN IF NOT EXISTS github_repo_id bigint  DEFAULT NULL;

-- Ensure github_repo_id has a unique constraint for upserts
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints 
    WHERE constraint_name = 'projects_github_repo_id_key' AND table_name = 'projects'
  ) THEN
    ALTER TABLE public.projects ADD CONSTRAINT projects_github_repo_id_key UNIQUE (github_repo_id);
  END IF;
END $$;

-- ============================================================
-- ALTER EXISTING: certificates → rename & extend
-- ============================================================
-- Rename table (safe; data preserved)
DO $$ BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'certificates'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'certifications'
  ) THEN
    ALTER TABLE public.certificates RENAME TO certifications;
  END IF;
END $$;

